// Rebuild lost runs from Claude Code's own transcripts.
// If state.json is lost (a disk or power failure), every run since the last
// good copy is still in ~/.claude/projects: one .jsonl per session, plus one per
// subagent. This splits each session into turns the way the hooks see them (a
// prompt opens a turn, Stop ends it), counts each turn with the same code the
// Stop hook uses (hooks/_activity.mjs), and writes runs.json for
//   node server.js --recover runs.json     (live server stopped first)
// which hatches them through the normal path, at their own times.
//
//   node scripts/recover-from-transcripts.mjs [--since <iso|ms>] [--until <iso|ms>]
//        [--projects <dir>] [--out runs.json] [--compare] [--list]
//
// --since defaults to the newest creature in your data folder. --compare matches
// the turns against creatures already on the shelf in that window (to check the
// rules) and writes nothing. Like the hooks, only counts and times are written:
// the prompt is read to pick a species key and then dropped.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { activityFromEntries, isPromptEntry } from '../hooks/_activity.mjs';

const require = createRequire(import.meta.url);
const { detectDomain } = require('../engine.js');
const Paths = require('../paths.js');

const args = process.argv.slice(2);
const flag = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const toMs = (v) => (v == null ? null : /^\d+$/.test(v) ? Number(v) : Date.parse(v));
const PROJECTS = flag('--projects') || path.join(os.homedir(), '.claude', 'projects');
const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const STATE = path.join(process.env.POL_DATA_DIR || Paths.dataDir(ROOT), 'state.json');
const HANDLE = flag('--handle');
const SUB_SLACK_MS = 5000;

function loadShelf() {
  try {
    const s = JSON.parse(fs.readFileSync(STATE, 'utf8'));
    const ops = Object.values(s.operators || {}).filter((o) => !o.sample);
    const op = HANDLE ? ops.find((o) => o.handle === HANDLE) : ops.sort((a, b) => b.creatures.length - a.creatures.length)[0];
    return op ? op.creatures : [];
  } catch { return []; }
}
const ts = (e) => { const t = Date.parse(e && e.timestamp); return isFinite(t) ? t : null; };
// line by line: a long session's transcript can pass Node's 512 MB string limit.
// Only entries inside [from, to] are kept (a day either side of the window), so
// a huge file never sits in memory whole. A power cut can leave runs of zero
// bytes in a transcript: they are skipped, and the line after them still reads.
// Each item is { e, end }: the entry and the byte offset just past its line, so
// the Stop hook's 4 MB tail (hooks/_activity.mjs MAX_BYTES) can be replayed.
function readJsonl(file, from, to) {
  const out = [];
  const fd = fs.openSync(file, 'r');
  const buf = Buffer.alloc(8 * 1024 * 1024);
  let rest = Buffer.alloc(0), n, pos = 0;
  const take = (line, end) => {
    let a = 0;
    while (a < line.length && line[a] === 0) a++;
    if (a >= line.length) return;
    let e;
    try { e = JSON.parse(line.subarray(a).toString('utf8')); } catch { return; }
    const t = ts(e);
    if (t != null && ((from && t < from) || (to && t > to))) return;
    out.push({ e, end });
  };
  while ((n = fs.readSync(fd, buf, 0, buf.length, null)) > 0) {
    let chunk = Buffer.concat([rest, buf.subarray(0, n)]);
    const base = pos - rest.length;
    let off = 0, i;
    while ((i = chunk.indexOf(10, off)) >= 0) { take(chunk.subarray(off, i), base + i + 1); off = i + 1; }
    rest = Buffer.from(chunk.subarray(off));
    pos += n;
  }
  take(rest, pos);
  fs.closeSync(fd);
  return out;
}

const textOf = (e) => {
  const c = e.message && e.message.content;
  if (typeof c === 'string') return c;
  return Array.isArray(c) ? c.filter((x) => x && x.type === 'text').map((x) => x.text || '').join('\n') : '';
};
// What fired UserPromptSubmit, so laid (or re-laid) the egg: a typed prompt, a
// scheduled-task prompt (stored as a meta entry) or a background-task notice.
// Not: tool results, image captions, interrupt markers, compaction summaries.
function opensEgg(x) {
  const e = x.e;
  if (e.type !== 'user' || !e.message || e.isCompactSummary || e.isVisibleInTranscriptOnly) return false;
  const c = e.message.content;
  if (Array.isArray(c) && (!c.some((b) => b && b.type === 'text') || c.some((b) => b && b.type === 'tool_result'))) return false;
  const t = textOf(e).trim();
  if (!t) return false;
  if (/^\[(Image: source|Request interrupted by user)/.test(t)) return false;
  if (/^<(local-command-stdout|local-command-caveat|bash-stdout|bash-input)/.test(t)) return false;
  if (/^Caveat: The messages below were generated by the user while running local commands/.test(t)) return false;
  return true;
}
// Claude Code writes this line right after the Stop hooks ran: the hatch moment
const isStop = (x) => x.e.type === 'system' && x.e.subtype === 'stop_hook_summary';
const TAIL_BYTES = 4 * 1024 * 1024; // hooks/_activity.mjs MAX_BYTES

function turnsOf(file, sessionId) {
  const items = readJsonl(file, since - 86400000, until + 86400000);
  const turns = [];
  let prevStop = -1;
  for (let k = 0; k < items.length; k++) {
    if (!isStop(items[k])) continue;
    const end = ts(items[k].e);
    // the egg's clock: the last prompt since the previous Stop (each one re-lays it)
    let p = -1;
    for (let j = k - 1; j > prevStop; j--) if (opensEgg(items[j])) { p = j; break; }
    prevStop = k;
    if (p < 0 || end == null) continue; // no egg was open, so the live Stop hatched nothing
    // the Stop hook read the transcript's last 4 MB and walked back to the last
    // typed prompt in it (hooks/_activity.mjs): replay exactly that
    const tailFrom = items[k - 1].end - TAIL_BYTES;
    let i0 = k - 1;
    while (i0 > 0 && items[i0 - 1].end - 1 >= tailFrom) i0--;
    const seen = items.slice(i0, k).map((x) => x.e);
    let i = seen.length - 1;
    while (i >= 0 && !isPromptEntry(seen[i])) i--;
    const activity = activityFromEntries(seen, i, true, false);
    const gaps = activity.gaps; delete activity.gaps;
    turns.push({ id: sessionId, start: ts(items[p].e), end, domain: detectDomain(textOf(items[p].e)), tzOffset: new Date(end).getTimezoneOffset(), activity, gaps, subagents: [] });
  }
  return turns;
}

function subagentsOf(dir) {
  const sd = path.join(dir, 'subagents');
  if (!fs.existsSync(sd)) return [];
  const out = [];
  // agent-*.jsonl, directly under subagents/ or deeper (subagents/workflows/<run>/)
  const files = [];
  const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/^agent-.*\.jsonl$/.test(f.name)) files.push(p); } };
  walk(sd);
  for (const file of files) {
    if (fs.statSync(file).mtimeMs < since - 86400000) continue;
    const entries = readJsonl(file, since - 86400000, until + 86400000).map((x) => x.e);
    let end = null;
    for (const e of entries) { const t = ts(e); if (t != null) end = Math.max(end || 0, t); }
    if (end == null) continue;
    const activity = activityFromEntries(entries, -1, false, false);
    out.push({ end, activity });
  }
  return out;
}

const shelf = loadShelf();
const since = toMs(flag('--since')) || shelf.reduce((m, c) => Math.max(m, c.bornAt || 0), 0);
const until = toMs(flag('--until')) || Date.now();
const runs = [];
for (const proj of fs.readdirSync(PROJECTS)) {
  const pdir = path.join(PROJECTS, proj);
  if (!fs.statSync(pdir).isDirectory()) continue;
  for (const f of fs.readdirSync(pdir)) {
    if (!f.endsWith('.jsonl')) continue;
    const file = path.join(pdir, f);
    if (fs.statSync(file).mtimeMs < since) continue; // nothing new in it
    const sessionId = f.slice(0, -6);
    const turns = turnsOf(file, sessionId).filter((t) => t.end >= since && t.end <= until);
    if (!turns.length) continue;
    for (const s of subagentsOf(path.join(pdir, sessionId))) {
      const t = turns.find((x) => x.start <= s.end && s.end <= x.end + SUB_SLACK_MS);
      if (t) t.subagents.push(s);
    }
    runs.push(...turns);
  }
}
runs.sort((a, b) => a.end - b.end);
const hatchable = runs.filter((r) => r.end - r.start >= 10000);
console.log(`turns ${runs.length}, 10 s or longer ${hatchable.length}, window ${new Date(since).toISOString()} .. ${new Date(until).toISOString()}`);

if (args.includes('--compare')) {
  const inWin = shelf.filter((c) => c.bornAt >= since && c.bornAt <= until);
  const used = new Set();
  let matched = 0, sameSpecies = 0, sameCalls = 0;
  const missed = [];
  for (const c of inWin) {
    const sid = String(c.id).split(':')[0];
    let best = -1, bestD = Infinity;
    hatchable.forEach((r, i) => { if (r.id !== sid || used.has(i)) return; const d = Math.abs(r.end - c.bornAt); if (d < bestD) { bestD = d; best = i; } });
    if (best >= 0 && bestD <= 60000) {
      used.add(best); matched++;
      const r = hatchable[best];
      const calls = (r.activity.toolCalls || 0) + r.subagents.reduce((n, s) => n + (s.activity.toolCalls || 0), 0);
      if (c.toolCalls === calls) sameCalls++;
      if (args.includes('--list')) console.log(`  match ${sid.slice(0, 8)} ${new Date(c.bornAt).toISOString().slice(5, 19)} d=${bestD}ms dur ${c.durationMs}/${r.end - r.start} calls ${c.toolCalls}/${calls} subs ${c.subagents}/${r.subagents.length} ${c.domainKey}`);
    } else missed.push(c);
  }
  const extra = hatchable.filter((r, i) => !used.has(i));
  console.log(`shelf ${inWin.length}: matched ${matched}, same tool calls ${sameCalls}, missed ${missed.length}; turns with no creature ${extra.length}`);
  if (args.includes('--list')) {
    for (const c of missed) console.log(`  missed ${String(c.id).slice(0, 8)} ${new Date(c.bornAt).toISOString().slice(5, 19)} dur ${c.durationMs}`);
    for (const r of extra) console.log(`  extra  ${r.id.slice(0, 8)} ${new Date(r.start).toISOString().slice(5, 19)} -> ${new Date(r.end).toISOString().slice(11, 19)} calls ${r.activity.toolCalls}`);
  }
} else {
  const out = flag('--out') || 'runs.json';
  fs.writeFileSync(out, JSON.stringify(runs));
  console.log(`wrote ${runs.length} runs to ${out}`);
}
